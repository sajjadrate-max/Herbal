// Vercel Serverless Function
// Route: POST /api/select-nuskha
//
// اس فائل کا مقصد: مریض کے مزاج، علامات اور بیماریوں کی بنیاد پر
// دی گئی دواؤں کی فہرست میں سے وہ دوا (یا دوائیں) منتخب کرنا جو
// سب سے جلد آرام دیں، اور اسی مزاج کی غذاؤں میں سے بھی موزوں ترین
// غذائیں منتخب کرنا — OpenAI API کی مدد سے۔
//
// اہم: OPENAI_API_KEY کبھی بھی کلائنٹ (براؤزر) کوڈ میں نہیں لکھنی —
// یہ صرف Vercel کے Environment Variables میں محفوظ رہنی چاہیے۔
//
// Vercel ڈیش بورڈ میں سیٹ اپ کا طریقہ:
// 1) Project → Settings → Environment Variables
// 2) Key: OPENAI_API_KEY   Value: <آپ کی اصل OpenAI API key>
// 3) Save کریں اور دوبارہ Deploy کریں (redeploy)

export default async function handler(req, res) {
  // صرف POST request قبول کریں
  if (req.method !== 'POST') {
    res.setHeader('Allow', ['POST']);
    return res.status(405).json({ error: 'صرف POST request قبول ہے۔' });
  }

  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) {
    return res.status(500).json({ error: 'سرور پر OPENAI_API_KEY سیٹ نہیں ہے۔ Vercel Environment Variables میں شامل کریں۔' });
  }

  try {
    const { mizaj, patientNumber, symptoms, diseases, candidates, foods, age, maritalStatus, diseaseDuration, bloodPressure, painTiming, sugar, qabz } = req.body || {};

    if (!Array.isArray(candidates) || candidates.length === 0) {
      return res.status(400).json({ error: 'دواؤں کی فہرست (candidates) خالی یا غلط ہے۔' });
    }

    // اب مزاج کی بنیاد پر پہلے سے چھانٹی نہیں ہوتی — تمام نسخے یہاں پہنچتے ہیں، اس لیے حد صرف حفاظتی ہے (لاگت/رفتار کے لیے)
    const limitedCandidates = candidates.slice(0, 150).map(c => ({
      name: c.name,
      mizaj: c.mizaj,
      benefit: (c.benefit || '').slice(0, 900) // ہر دوا کا فائدہ محدود لمبائی تک
    }));

    const foodList = Array.isArray(foods) ? foods.slice(0, 80) : [];

    const symptomsText = Array.isArray(symptoms) && symptoms.length ? symptoms.join('، ') : 'کوئی خاص علامت نہیں بتائی گئی';
    const diseasesText = Array.isArray(diseases) && diseases.length ? diseases.join('، ') : 'کوئی خاص بیماری منتخب نہیں کی گئی';

    const systemPrompt = `آپ ایک تجربہ کار معالج ہیں جو "قانونِ مفرد اعضاء" کے اصولوں کے ماہر ہیں۔

اہم: نیچے تمام دستیاب نسخوں کی مکمل فہرست دی گئی ہے — یہ کسی ایک مزاج کیٹیگری تک پہلے سے محدود نہیں کی گئی، تاکہ مریض کی اصل بیماری/علامت سے میل کھانے والا نسخہ کسی بھی مزاج گروپ سے چنا جا سکے۔ مریض کا مزاج (نیچے یوزر پیغام میں دیا گیا ہے) صرف اضافی معلومات کے طور پر ہے، اسے فہرست کو محدود کرنے کے لیے استعمال نہ کریں۔ آپ کا کام صرف اسی فہرست میں سے وہ دوا/دوائیں منتخب کرنا ہے جن کے فوائد میں مریض کی بتائی گئی بیماری/علامات کا لفظی یا قریبی مفہومی تعلق سب سے زیادہ واضح ہو — چاہے وہ نسخہ کسی بھی مزاج گروپ سے تعلق رکھتا ہو۔ اسی طرح دی گئی غذاؤں کی فہرست میں سے بھی بیماری/علامات کے مطابق موزوں ترین غذائیں منتخب کرنی ہیں۔

دوا کے انتخاب کا اصول — دوا صرف اس کے حقیقی "فوائد" اور اس کی قسم کے حقیقی استعمال کی بنیاد پر منتخب کی جائے گی، کبھی زبردستی نہیں تھوپی جائے گی:
1) دی گئی فہرست میں سے وہ دوا/دوائیں منتخب کریں جن کے "فوائد" مریض کی بتائی گئی بیماری/علامت سے واقعی اور حقیقی طور پر تعلق رکھتے ہوں — پہلے لفظی/صاف میل تلاش کریں، اگر صاف لفظی میل نہ ملے تو مفہومی اعتبار سے قریب ترین دوا تلاش کریں، لیکن یہ تعلق حقیقی ہونا چاہیے، فرضی یا کھینچ تان کر بنایا ہوا نہیں۔ عمر، بلڈ پریشر، شوگر، بیماری کی مدت، تکلیف کا وقت، یا ازدواجی حیثیت — انتخاب کی بنیاد نہیں بنیں گے، البتہ نیچے نکتہ (3) میں دی گئی قسم کی شرائط (کمزوری/بڑھاپا/پرانا مریض وغیرہ) ضرور مدنظر رکھیں کیونکہ یہ خود دوا کی قسم کے حقیقی استعمال کا حصہ ہیں۔
2) ہر انتخاب کی "reason" میں لازمی طور پر دوا کے "benefit" میں سے وہ لفظ/فقرہ نقل کریں جو مریض کی بیماری/علامت سے حقیقی طور پر میل کھاتا ہے — عمومی، فرضی، یا غیر متعلقہ وجہ ہرگز نہ لکھیں۔ اگر "benefit" میں علامت کا کوئی حقیقی تعلق موجود نہیں تو وہ دوا منتخب نہ کریں، چاہے کوئی اور موزوں دوا نہ ملے۔
2الف) صرف "ایک ہی موضوع" (مثلاً سانس/کھانسی/دمہ) کا اشتراک کافی نہیں — تفصیلات کا بھی ملنا ضروری ہے۔ اگر مریض کی بیماری کسی خاص کیفیت کی وضاحت کے ساتھ بتائی گئی ہو (مثلاً "بلغمی/تر" دمہ یا کھانسی)، تو ایسی دوا ہرگز منتخب نہ کریں جس کا "benefit" اس کے برعکس یا مختلف کیفیت کے لیے لکھا گیا ہو (مثلاً "خشک کھانسی" کے لیے دوا — یہ بلغمی/تر کھانسی یا دمہ کے لیے مماثل شمار نہیں ہوگی، اور اس کے برعکس بھی)۔ اسی طرح اگر دوا کا "benefit" کسی بالکل مختلف موضوع (مثلاً جوڑوں/پٹھوں کی تکلیف) کے لیے ہے تو اسے مریض کی بیان کردہ بیماری (مثلاً دمہ) کے لیے ہرگز منتخب نہ کریں، چاہے دونوں ایک ہی مزاج گروپ میں ہوں — مزاج کی مطابقت کبھی بھی بیماری کی مطابقت کا متبادل نہیں۔ ہر دوا کے "benefit" کے پورے متن کو غور سے پڑھ کر یہ یقینی بنائیں کہ وہ اسی مخصوص بیماری/کیفیت کے لیے ہے، نہ کہ کسی اور بیماری یا مخالف کیفیت کے لیے۔

نسخوں کی قسم (نام کے آخری لفظ) کا حقیقی استعمال — ہر قسم صرف اپنے مخصوص موقع پر ہی تجویز ہو، کسی اور علامت کے لیے پُر کرنے کی خاطر ہرگز نہ دی جائے:
- ملین: قبض ہلکے طریقے سے کھولنے کے لیے۔
- مسہل: صرف قبض، خارش/پھوڑے پھنسیاں (جلدی امراض)، یا فاسد اخلاط/مادہ کو تیزی سے خارج کرنے کی ضرورت ہو تب دی جاتی ہے — گیس، بھاری پن، یا اس نوعیت کی دیگر علامات کے لیے ہرگز تجویز نہ کریں، جب تک بیان کردہ علامت خود قبض/خارش/پھوڑے پھنسیاں/فاسد مادہ کے اخراج سے متعلق نہ ہو۔
- اکسیر: شدید یا دائمی/پرانی بیماری کے لیے مرتکز دوا۔
- تریاق: زہر، خون کا اخراج، شدید درد، یا بحرانی کیفیت کے فوری تدارک کے لیے۔
- ہاضم: ہاضمہ کی خرابی کے لیے۔
- معجون/جوارش/لبوب/اطریفل/حلوہ/خمیرہ/مفرح (جیسے مفرح شاہی): یہ عمومی مقوی (tonic) دوائیں ہیں — یہ صرف اسی وقت تجویز کریں جب مریض کمزور ہو، بڑی عمر کا ہو، یا پرانا/دائمی مریض ہو۔ محض کسی نئی یا غیر متعلقہ علامت (مثلاً گیس) کے لیے فالتو طور پر تجویز نہ کریں۔
- طلاء/روغن/مرہم/لیپ/سفوف (بیرونی)/نکور: صرف بیرونی استعمال کے لیے — اندرونی بیماری میں تجویز نہ کریں۔
- شربت/حب/کیپسول/سفوف (اندرونی): فوائد دیکھ کر فیصلہ کریں۔

3) اگر فہرست میں کوئی دوا مریض کی علامت سے حقیقی طور پر میل نہیں کھاتی (نہ لفظی نہ مفہومی، اور نہ ہی اوپر دی گئی قسم کی شرائط پوری ہوتی ہوں)، تو اسے ہرگز منتخب نہ کریں — ایسی صورت میں فہرست میں سے وہی دوائیں دیں جن کا واقعی تعلق ہو، خواہ وہ تعداد میں کم ہوں۔ صرف اسی صورت میں خالی "selections": [] دیں جب فہرست میں کوئی دوا بھی علامت سے حقیقی تعلق نہ رکھتی ہو۔
4) زیادہ سے زیادہ 3 دوائیں منتخب کریں، اور جو سب سے زیادہ درست میل کھاتی ہو اسے پہلے نمبر پر رکھیں۔

غذاؤں کے انتخاب کا اصول:
5) نیچے دی گئی غذاؤں کی فہرست میں سے صرف وہی 5 سے 8 غذائیں منتخب کریں جو مریض کی بتائی گئی بیماری/علامات کے لیے روایتی حکمت کے مطابق خاص طور پر مفید ہوں۔ فہرست سے باہر کوئی غذا تجویز نہ کریں۔ اگر غذاؤں کی فہرست نہ دی گئی ہو یا کوئی خاص میل نہ کھائے تو خالی "foodSelections": [] واپس کریں۔

جواب صرف اس JSON شکل میں دیں، کوئی اضافی متن نہیں:
{"selections":[{"name":"دوا کا صحیح نام (فہرست سے بالکل ویسا)","reason":"مختصر وجہ اردو میں، جس میں دوا کے فوائد سے وہ عین لفظ/فقرہ شامل ہو جو مریض کی بیماری/علامت سے میل کھاتا ہے"}],"foodSelections":[{"name":"غذا کا نام (فہرست سے بالکل ویسا)","reason":"مختصر وجہ اردو میں"}]}`;

    const userPrompt = `مریض کا مزاج: ${mizaj || 'نامعلوم'}${patientNumber ? ' (نمبر ' + patientNumber + ')' : ''}
عمر: ${age || 'نامعلوم'}
بیماری کب سے ہے (نئی/پرانی): ${diseaseDuration || 'نامعلوم'}
علامات: ${symptomsText}
بیماریاں: ${diseasesText}

دستیاب دواؤں کی فہرست:
${limitedCandidates.map((c, i) => `${i + 1}. ${c.name} — مزاج: ${c.mizaj} — فوائد: ${c.benefit}`).join('\n')}

دستیاب غذاؤں کی فہرست:
${foodList.length ? foodList.join('، ') : '(کوئی غذائی فہرست فراہم نہیں کی گئی)'}`;

    const openaiRes = await fetch('https://api.openai.com/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${apiKey}`
      },
      body: JSON.stringify({
        model: 'gpt-4o-mini',
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: userPrompt }
        ],
        temperature: 0.3,
        response_format: { type: 'json_object' }
      })
    });

    if (!openaiRes.ok) {
      const errBody = await openaiRes.text().catch(() => '');
      return res.status(502).json({ error: 'OpenAI API سے جواب نہیں ملا۔', details: errBody });
    }

    const data = await openaiRes.json();
    const content = data.choices && data.choices[0] && data.choices[0].message && data.choices[0].message.content;

    if (!content) {
      return res.status(502).json({ error: 'جواب خالی تھا۔' });
    }

    let parsed;
    try {
      parsed = JSON.parse(content);
    } catch (e) {
      return res.status(502).json({ error: 'جواب صحیح فارمیٹ میں نہیں تھا۔' });
    }

    if (!parsed.selections || !Array.isArray(parsed.selections)) {
      return res.status(502).json({ error: 'جواب میں دوائیوں کی فہرست موجود نہیں۔' });
    }

    const foodSelections = Array.isArray(parsed.foodSelections) ? parsed.foodSelections : [];

    return res.status(200).json({ selections: parsed.selections, foodSelections });

  } catch (err) {
    console.error('select-nuskha error:', err);
    return res.status(500).json({ error: 'سرور میں خرابی پیش آئی۔', details: String(err && err.message ? err.message : err) });
  }
}
